class TestWorkflowHardening:
    def test_least_privilege_and_no_credential_persistence(self):
        text = WORKFLOW.read_text(encoding="utf-8")
        assert re.search(r"^permissions:\s*$\n^\s{2}contents:\s*read\s*$", text, re.MULTILINE)
        assert "persist-credentials: false" in text
        assert re.search(r"^\s{4}timeout-minutes:\s*\d+\s*$", text, re.MULTILINE)

    def test_no_continue_on_error_anywhere(self):
        assert "continue-on-error" not in WORKFLOW.read_text(encoding="utf-8")

    def test_pack_step_parses_the_artifact_verdict(self):
        text = WORKFLOW.read_text(encoding="utf-8")
        pack_step = _step_block(text, "Release evidence pack")
        assert "release_pack.py" in pack_step
        assert "release_pack.json" in pack_step
        # Only the explicit engineering verdict passes; everything else is red.
        assert "engineering_pass_clinical_blocked" in pack_step
        assert "overall" in pack_step

    def test_pack_step_excludes_stale_artifacts_and_requires_a_fresh_verdict(self):
        block = _step_block(WORKFLOW.read_text(encoding="utf-8"), "Release evidence pack")
        # A crash exit (e.g. 137) must not be able to read an old artifact's
        # verdict: the previous pack is deleted before the run.
        assert "rm -f outputs/release_pack.json" in block
        # Exit 0 is green only with overall==pass; exit 1 only with the
        # engineering verdict. Any other combination falls through to failure.
        assert '"$status" -eq 0' in block and '"$overall" = "pass"' in block
        assert '"$status" -eq 1' in block and '"$overall" = "engineering_pass_clinical_blocked"' in block

    def test_recovery_drill_step_name_matches_the_scenario_count(self):
        from medcopilot.scripts.recovery_drill import SCENARIOS

        text = WORKFLOW.read_text(encoding="utf-8")
        assert f"Recovery drill ({len(SCENARIOS)} scenarios)" in text

    def test_load_check_profile_matches_the_pack_gate(self):
        from medcopilot.scripts.release_pack import GATES

        ci_step = _code_only(_step_block(WORKFLOW.read_text(encoding="utf-8"), "Load check"))
        pack_command = GATES["load_check"]["command"]
        for flag in ("--concurrency", "--requests-per-worker"):
            match = re.search(rf"{flag}\s+(\d+)", ci_step)
            assert match, f"CI load check must pin {flag}"
            assert match.group(1) in pack_command, (
                f"pack load_check gate must use the same {flag} as the CI step"
            )

    def test_redaction_scan_runs_after_the_pack_it_must_cover(self):
        text = WORKFLOW.read_text(encoding="utf-8")
        assert text.index("- name: Release evidence pack") < text.index("- name: Redaction scan")
        redact_step = _code_only(_step_block(text, "Redaction scan"))
        assert "redact_scan.py outputs" in redact_step
        assert "--output" not in redact_step, "the external scan must not race the pack's summary"


def _step_block(text: str, step_name: str) -> str:
    """Return the YAML block of one step (from its `- name:` to the next step)."""
    start = text.index(f"- name: {step_name}")
    following = text.find("- name: ", start + 1)
    return text[start : len(text) if following == -1 else following]


def _code_only(block: str) -> str:
    """Comment lines explain why; only executable lines carry the guarantee."""
    return "\n".join(line for line in block.splitlines() if not line.lstrip().startswith("#"))


