"""Engineering hardening contracts for the release/ops toolchain.

Each test is hermetic: no gate subprocess is really executed (``subprocess.run``
is mocked where a gate would run), no ``uv export`` touches the network
(``--locked --offline`` is pinned by flag assertions plus a mocked render), and
no checkpoint is loaded — the local torch is below the safety floor, so nothing
here may reach ``torch.load``.

Covers, in order:

1. ``export_lock`` — byte-stable render (no per-run temp path in the file),
   hashes/annotations preserved, hermetic export flags, ``--check`` verdicts.
2. ``redact_scan`` — a missing scan target is a failure, not a clean tree.
3. ``release_pack`` — gate stdout/stderr tails are scrubbed through the shared
   ``UnifiedLLM._redact`` before they enter the evidence bundle, and the
   clinical-blocked verdict only appears when it is actually earned.
4. CI workflow — least privilege, no ``continue-on-error`` laundering, the
   evidence-pack verdict parsed from the artifact, the redaction scan ordered
   after the pack it must cover.
5. Packaging / image context — namespace subpackages stay installable, junk
   directories stay out, and no rule may exclude the approved datasets.
6. ``conftest`` — per-process temp isolation for the log and audit sinks,
   including spawned children, without touching the repo's prod logs or any
   HuggingFace cache.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
