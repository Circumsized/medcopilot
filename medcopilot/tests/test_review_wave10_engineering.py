class TestPackaging:
    def test_namespace_subpackages_survive_and_junk_directories_do_not(self):
        pytest.importorskip("setuptools")
        from setuptools import find_namespace_packages

        config = _packages_find_config()
        # find_namespace_packages is itself the namespace-aware finder (it takes
        # no `namespaces` flag), and `where` is absolute so the result does not
        # depend on the pytest working directory.
        packages = find_namespace_packages(
            where=str(REPO_ROOT),
            include=config["include"],
            exclude=config["exclude"],
        )
        for keep in (
            "medcopilot.scripts",
            "medcopilot.ui",
            "medcopilot.api",
            "medcopilot.datasets",
            "medcopilot.common",
        ):
            assert keep in packages, f"{keep} must stay installable"
        for drop in (
            "medcopilot.logs",
            "medcopilot.outputs",
            "medcopilot.docs",
            "medcopilot.tests",
        ):
            assert drop not in packages, f"{drop} must not be packaged"

    def test_namespaces_flag_stays_true(self):
        assert _packages_find_config()["namespaces"] is True


def _packages_find_config() -> dict:
    text = PYPROJECT.read_text(encoding="utf-8")
    match = re.search(
        r"\[tool\.setuptools\.packages\.find\](.*?)(?=\n\[|\Z)", text, re.DOTALL
    )
    assert match, "pyproject must declare [tool.setuptools.packages.find]"
    # Comment lines may legitimately spell out ``namespaces = false`` in prose
    # (explaining why the flag stays true); only code lines carry the config.
    section = "\n".join(
        line for line in match.group(1).splitlines() if not line.lstrip().startswith("#")
    )
    include = re.search(r"include\s*=\s*\[(.*?)\]", section, re.DOTALL).group(1)
    exclude = re.search(r"exclude\s*=\s*\[(.*?)\]", section, re.DOTALL).group(1)
    namespaces = re.search(r"^namespaces\s*=\s*(true|false)\s*$", section, re.MULTILINE)
    assert namespaces, "namespaces must be set explicitly under packages.find"
    return {
        "include": re.findall(r'"([^"]+)"', include),
        "exclude": re.findall(r'"([^"]+)"', exclude),
        "namespaces": namespaces.group(1) == "true",
    }


class TestDockerignore:
    def test_junk_is_excluded_and_datasets_are_protected(self):
        patterns = [
            line.strip()
            for line in DOCKERIGNORE.read_text(encoding="utf-8").splitlines()
            if line.strip() and not line.strip().startswith("#")
        ]
        for needed in ("**/docs", "**/tests", "**/logs", "**/outputs", ".uv-cache", ".venv-supply"):
            assert needed in patterns, needed
        # No rule may match the approved, git-tracked datasets (nor any nested
        # data directory); only the root-level local training tree is dropped.
        assert "**/data" not in patterns
        assert "**/datasets" not in patterns
        assert "datasets" not in patterns
        assert "data" in patterns
        assert "**/data" not in patterns

    def test_no_rule_matches_the_approved_datasets_directory(self):
        datasets_dir = REPO_ROOT / "medcopilot" / "datasets"
        assert datasets_dir.is_dir(), "the approved datasets tree must exist"
        relative = datasets_dir.relative_to(REPO_ROOT).as_posix()
        patterns = [
            line.strip()
            for line in DOCKERIGNORE.read_text(encoding="utf-8").splitlines()
            if line.strip() and not line.strip().startswith("#") and not line.startswith("!")
        ]
        offenders = [
            pattern for pattern in patterns if _dockerignore_matches(pattern, relative)
        ]
        assert not offenders, f".dockerignore would exclude the approved datasets: {offenders}"


def _dockerignore_matches(pattern: str, relative_posix: str) -> bool:
    """Conservative Docker-ignore matcher for the dataset-protection assertion.

    ``**`` spans path separators, ``*`` does not; a pattern without a separator
    matches at the root only, mirroring Docker's ``filepath.Match`` semantics.
    """
    import fnmatch

    if "/" not in pattern:
        return fnmatch.fnmatch(relative_posix.split("/")[0], pattern)
    if not pattern.startswith("**/"):
        return fnmatch.fnmatch(relative_posix, pattern)
    parts = relative_posix.split("/")
    return any(fnmatch.fnmatch("/".join(parts[index:]), pattern[3:]) for index in range(len(parts)))


