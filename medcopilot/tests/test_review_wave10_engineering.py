class TestExportLock:
    def test_export_is_hermetic_and_header_free(self):
        from medcopilot.scripts import export_lock

        args = export_lock.EXPORT_ARGS
        assert args[:2] == ("export", "--format") and args[2] == "requirements-txt"
        for flag in ("--no-emit-project", "--no-emit-local", "--no-header", "--locked", "--offline"):
            assert flag in args, flag
        # Hash emission must never be disabled: the hashes are the security property.
        assert "--no-hashes" not in args

    def test_render_is_stable_and_keeps_hashes_annotations_and_pins(self, monkeypatch):
        from medcopilot.scripts import export_lock

        payload = (
            "torch==2.14.1+cpu ; sys_platform != 'darwin' \\\n"
            "    --hash=sha256:aaa\n"
            "fastapi==0.142.2 \\\n"
            "    --hash=sha256:bbb\n"
            "    # via\n"
            "    #   typer\n"
        )
        seen_commands = []

        def fake_run(command, **kwargs):
            seen_commands.append(command)
            output = Path(command[command.index("--output-file") + 1])
            output.write_text(payload, encoding="utf-8")
            return subprocess.CompletedProcess(command, 0, stdout="", stderr="")

        monkeypatch.setattr(export_lock.subprocess, "run", fake_run)
        first = export_lock.render()
        second = export_lock.render()
        assert first == second, "render must be byte-stable across runs"
        # The temporary output path and uv's autogenerated banner never enter the file.
        assert "autogenerated" not in first and "tmp" not in first
        assert "--hash=sha256:aaa" in first and "--hash=sha256:bbb" in first
        assert "# via" in first, "per-package provenance annotations must survive"
        assert "torch==2.14.1 ; sys_platform != 'darwin'" in first
        assert "+cpu" not in first, "local-version segments are unauditable"
        # The flags that make it hermetic are actually passed to uv.
        for command in seen_commands:
            assert "--no-header" in command and "--locked" in command and "--offline" in command

    def test_check_verdicts(self, monkeypatch, tmp_path):
        from medcopilot.scripts import export_lock

        monkeypatch.setattr(
            export_lock.subprocess, "run",
            lambda command, **kwargs: (
                Path(command[command.index("--output-file") + 1]).write_text("torch==2.14.1\n", encoding="utf-8"),
                subprocess.CompletedProcess(command, 0, stdout="", stderr=""),
            )[1],
        )
        current = tmp_path / "requirements.lock.txt"
        current.write_text("torch==2.14.1\n", encoding="utf-8")
        assert export_lock.main(["--check", "--output", str(current)]) == 0
        current.write_text("torch==2.14.0\n", encoding="utf-8")
        assert export_lock.main(["--check", "--output", str(current)]) == 1

    def test_missing_uv_fails_loudly(self, monkeypatch):
        from medcopilot.scripts import export_lock

        monkeypatch.setattr(export_lock.shutil, "which", lambda _name: None)
        with pytest.raises(SystemExit):
            export_lock._uv()


