def _gate_with_output(stdout: str, stderr: str, *, timeout: bool = False):
    """A mocked subprocess.run that hands release_pack a canned gate result."""
    command = [sys.executable, "gate.py"]

    def fake_run(cmd, **kwargs):
        if timeout:
            raise subprocess.TimeoutExpired(cmd, 1, output=stdout, stderr=stderr)
        return subprocess.CompletedProcess(cmd, 2, stdout=stdout, stderr=stderr)

    return fake_run, command


class TestPackTailRedaction:
    def test_gate_tails_are_scrubbed_before_entering_the_pack(self, monkeypatch):
        from medcopilot.scripts import release_pack

        fake_run, command = _gate_with_output(
            f" contacting provider Authorization: Bearer {SECRET_BEARER}\nplain FAIL (faithfulness) line",
            f"error: ?{SECRET_QUERY} refused",
        )
        monkeypatch.setattr(release_pack.subprocess, "run", fake_run)
        monkeypatch.setitem(
            release_pack.GATES,
            "_test_redact",
            {"command": command, "required": True, "expected_status": "pass", "env": {}},
        )
        gate = release_pack._run_gate("_test_redact")
        joined = "\n".join(gate["stdout_tail"] + gate["stderr_tail"])
        assert SECRET_BEARER not in joined and SECRET_QUERY not in joined
        assert "***" in joined
        assert "plain FAIL (faithfulness) line" in joined, "redaction must not eat gate verdicts"

    def test_timeout_partial_output_is_scrubbed_too(self, monkeypatch):
        from medcopilot.scripts import release_pack

        fake_run, command = _gate_with_output(
            f"Authorization: Bearer {SECRET_BEARER}", "", timeout=True,
        )
        monkeypatch.setattr(release_pack.subprocess, "run", fake_run)
        monkeypatch.setitem(
            release_pack.GATES,
            "_test_timeout_redact",
            {"command": command, "required": True, "expected_status": "pass", "env": {}},
        )
        gate = release_pack._run_gate("_test_timeout_redact")
        assert gate["status"] == "crash"
        joined = "\n".join(gate["stdout_tail"] + gate["stderr_tail"])
        assert SECRET_BEARER not in joined
        assert "***" in joined, "the partial output must survive (scrubbed), not vanish"

    def test_clinical_blocked_requires_an_actually_unsigned_signoff(self, monkeypatch):
        """The verdict is earned, not assumed: a signed-off pack is a plain pass."""
        from medcopilot.scripts import release_pack

        monkeypatch.setattr(
            release_pack, "_run_gate",
            lambda name, overrides=None: {
                "name": name, "required": release_pack.GATES[name]["required"], "status": "pass",
                "exit_code": 0, "duration_seconds": 0,
            },
        )
        pack = release_pack.build_pack(list(release_pack.GATES), profile="opensource", evidence_paths={})
        assert pack["overall"] == "pass", "a fully signed-off pack is a plain pass"
        assert pack["overall"] != "engineering_pass_clinical_blocked"


class TestOpsGateExitCodes:
    """recovery_drill / load_check / redact_scan document exit 1 as an ordinary
    failure (the report is still written), so their spec must declare ``[0, 1]``.
    With ``[0]`` alone a real failure would be misreported as a tool crash; the
    exit-2 (and beyond) crash discrimination must stay intact, and an ordinary
    exit-1 failure on a required gate must still hard-block the overall verdict.
    """

    OPS_GATES = ("recovery_drill", "load_check", "redact_scan")

    def test_ops_gates_declare_exit_one_as_an_explained_failure(self):
        from medcopilot.scripts.release_pack import GATES

        for name in self.OPS_GATES:
            assert GATES[name]["expected_exit_codes"] == [0, 1], name

    def test_ops_gate_exit_one_is_fail_and_exit_two_is_crash(self):
        from medcopilot.scripts.release_pack import GATES, gate_status

        for name in self.OPS_GATES:
            spec = GATES[name]
            codes = spec["expected_exit_codes"]
            assert gate_status(0, spec["required"], spec["expected_status"], codes) == "pass"
            assert gate_status(1, spec["required"], spec["expected_status"], codes) == "fail"
            assert gate_status(2, spec["required"], spec["expected_status"], codes) == "crash"

    def test_hand_written_gates_omit_codes_and_keep_legacy_semantics(self):
        """Omitted (None) is not the same as an explicit [0]: any non-zero is a
        plain failure, with no crash discrimination."""
        from medcopilot.scripts.release_pack import GATES, gate_status

        for name in ("unit_tests", "golden_gate", "policy_gate"):
            assert GATES[name].get("expected_exit_codes") is None, name
        assert gate_status(1, True, "pass", None) == "fail"
        assert gate_status(2, True, "pass", None) == "fail"

    def test_report_gate_helper_default_stays_strict(self):
        from medcopilot.scripts.release_pack import _report_gate

        spec = _report_gate("probe", [sys.executable, "probe.py"])
        assert spec["expected_exit_codes"] == [0]
        assert spec["required"] is True and spec["expected_status"] == "pass"

    def test_required_ops_failure_still_blocks_overall(self):
        from medcopilot.scripts.release_pack import aggregate_gates, gate_status

        status = gate_status(1, True, "pass", [0, 1])
        assert status == "fail"
        assert aggregate_gates([{"name": "load_check", "required": True, "status": status}]) == "fail"


