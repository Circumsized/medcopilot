class TestConftestIsolation:
    _REPORT_CODE = (
        "import conftest, json, os\n"
        "print(json.dumps({k: os.environ.get(k, '') for k in "
        "('LOG_FILE', 'AUDIT_LOG_PATH', 'HF_HOME', 'HF_HUB_OFFLINE')}))\n"
    )

    def _spawn_env_report(self, *, clean: bool = False) -> dict:
        env = dict(os.environ)
        if clean:
            for key in ("LOG_FILE", "AUDIT_LOG_PATH", "HF_HOME", "HF_HUB_OFFLINE", "TRANSFORMERS_CACHE"):
                env.pop(key, None)
        env["PYTHONPATH"] = "."
        completed = subprocess.run(
            [sys.executable, "-c", self._REPORT_CODE], cwd=REPO_ROOT, env=env,
            capture_output=True, text=True, timeout=120,
        )
        assert completed.returncode == 0, completed.stderr
        return json.loads(completed.stdout.strip().splitlines()[-1])

    def test_clean_process_gets_per_pid_temp_paths_not_repo_logs(self):
        report = self._spawn_env_report(clean=True)
        temp_root = Path(os.path.realpath(tempfile.gettempdir()))
        for key in ("LOG_FILE", "AUDIT_LOG_PATH"):
            value = report[key]
            assert value, f"{key} must be set"
            resolved = Path(os.path.realpath(value))
            assert temp_root in resolved.parents, f"{key} must live in the temp dir: {value}"
            assert REPO_ROOT not in resolved.parents, f"{key} must not touch the repo: {value}"
        # Two processes must not share a sink.
        other = self._spawn_env_report(clean=True)
        assert other["LOG_FILE"] != report["LOG_FILE"]
        assert other["AUDIT_LOG_PATH"] != report["AUDIT_LOG_PATH"]

    def test_conftest_does_not_touch_any_huggingface_cache(self):
        report = self._spawn_env_report(clean=True)
        assert report["HF_HOME"] == "" and report["HF_HUB_OFFLINE"] == ""

    def test_spawned_child_does_not_inherit_the_parent_sink(self):
        """The patched Popen re-points inherited managed paths per spawn."""
        code = (
            "import json, os\n"
            "print(json.dumps({k: os.environ.get(k, '') for k in ('LOG_FILE', 'AUDIT_LOG_PATH')}))\n"
        )
        report = subprocess.run(
            [sys.executable, "-c", code], cwd=REPO_ROOT,
            capture_output=True, text=True, timeout=120,
        )
        assert report.returncode == 0, report.stderr
        child = json.loads(report.stdout.strip().splitlines()[-1])
        assert child["LOG_FILE"] != os.environ["LOG_FILE"]
        assert child["AUDIT_LOG_PATH"] != os.environ["AUDIT_LOG_PATH"]
        assert Path(child["LOG_FILE"]).parent != Path(os.environ["LOG_FILE"]).parent

