"""Regenerate the hash-locked requirements files from ``uv.lock`` (W5.2 / W11).

One ``uv.lock`` is the single source of truth; this script renders it into one
*profile* per invocation so every install/audit surface in the repo is a
byte-stable projection of the same resolution. The profiles mirror the
dependency surfaces the repository actually has:

* ``base``  — the runtime install set (what the Docker image installs).
* ``ci``    — base + the ``dev`` extra: what CI tests against.
* ``rag`` / ``eval`` / ``ocr`` — the optional extras. Their
  vulnerability surface is just as real as the base one, so each gets its own
  auditable lock instead of silently shipping unaudited.
* ``build`` / ``tools`` — the ``build`` and ``supply-chain`` dependency groups.

Why this script exists instead of a raw ``uv export``:

* The image installs CPU-only torch wheels (``torch==2.14.1+cpu``), which live on
  the PyTorch index, not PyPI. A local-version pin cannot be audited by
  ``pip-audit`` (it looks the package up on PyPI by name==version and reports
  "Dependency not found on PyPI"), so ``--strict`` fails — and the same string
  cannot be resolved from PyPI alone.
* Dropping the local segment keeps the security property intact: the file stays
  fully pinned **and** hash-pinned, and only the CPU wheel's hash is listed, so
  ``--require-hashes`` still binds the install to that exact file. What changes
  is only how the pin is *spelled* (``torch==2.14.1``), which PyPI and the audit
  service can both resolve.
* Any substitution attempt (a different wheel claiming the same version) fails
  the hash check, so this is not a loosening of the guarantee.
* The render is byte-stable so ``--check`` is meaningful: ``--no-header`` drops
  uv's autogenerated header, which embeds this script's per-run temporary
  ``--output-file`` path and the invoking machine's ``--cache-dir`` and would
  otherwise make every render differ from the last one (the pre-W11 extras
  locks carried exactly that machine-specific header). Index pins come from
  ``uv.lock`` itself and the CPU index is declared by the *consumers*
  (Dockerfile / CI pass ``--extra-index-url
  https://download.pytorch.org/whl/cpu``, pinned by ``test_supply_chain_lock.py``) —
  these files carry hashes and ``# via`` provenance only. Refreshing the lock is
  ``uv lock``'s job; exporting never re-resolves or touches the network
  (``--locked --offline``).

Usage::

    python medcopilot/scripts/export_lock.py                      # regenerate base
    python medcopilot/scripts/export_lock.py --profile rag        # regenerate one profile
    python medcopilot/scripts/export_lock.py --profile ci --check # verify freshness
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]

# profile -> (extra uv export flags, output file name). One profile per
# invocation: standard flags, no batching abstraction — CI loops over the names.
PROFILES: dict[str, tuple[tuple[str, ...], str]] = {
    "base": ((), "requirements.lock.txt"),
    "ci": (("--no-dev", "--extra", "dev"), "requirements-ci.lock.txt"),
    "rag": (("--no-dev", "--extra", "rag"), "requirements-rag.lock.txt"),
    "eval": (("--no-dev", "--extra", "eval"), "requirements-eval.lock.txt"),
    "ocr": (("--no-dev", "--extra", "ocr"), "requirements-ocr.lock.txt"),
    "build": (("--only-group", "build"), "requirements-build.lock.txt"),
    "tools": (("--only-group", "supply-chain"), "requirements-tools.lock.txt"),
}
# A pin such as torch==2.14.1+cpu -> torch==2.14.1 (kept in the same requirement
# line together with its --hash continuations).
_LOCAL_VERSION = re.compile(r"^(?P<name>[A-Za-z0-9][A-Za-z0-9_.-]*)==(?P<version>[^;\\+\s]+)\+[^;\\\s]+(?P<rest>.*)$")


def _semantic_pins(text: str) -> list[tuple[str, ...]]:
    """Platform-independent signature of a rendered lock file.

    uv export's marker boolean simplification follows the *generating* platform's
    evaluation path: the same truth-value condition renders as different-but-equivalent
    marker strings on Windows vs Linux (e.g. colorama's os_name/sys_platform
    condition). Byte equality therefore false-negatives a cross-platform freshness
    gate. The supply-chain trust root is the (name==version, ordered --hash set)
    pair per pin block; markers are install conditions only, so the signature
    compares those pairs as a sorted multiset and ignores comments/markers.
    """
    pins: list[tuple[str, ...]] = []
    block: list[str] = []
    for raw in text.splitlines():
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            if block:
                pins.append(tuple(sorted(block)))
                block = []
            continue
        entry = raw.rstrip().rstrip("\\").strip()
        if "==" in entry and ";" in entry:
            entry = entry.split(";", 1)[0].strip()
        block.append(entry)
        if not raw.rstrip().endswith("\\"):
            pins.append(tuple(sorted(block)))
            block = []
    if block:
        pins.append(tuple(sorted(block)))
    return sorted(pins)
EXPORT_ARGS = (
    "export",
    "--format", "requirements-txt",
    "--no-emit-project",
    "--no-emit-local",
    # The header embeds the per-run temporary --output-file path and the
    # invoking machine's --cache-dir, so keeping it makes --check structurally
    # unsatisfiable. Supported since well before the CI-pinned uv 0.11.16.
    "--no-header",
    # The committed uv.lock is the input: exporting must never re-resolve,
    # upgrade, or reach the network (a reproducible lock is the whole point).
    "--locked",
    "--offline",
)


def _uv() -> str:
    found = shutil.which("uv")
    if not found:
        raise SystemExit("FAIL: uv is not on PATH; install uv to regenerate the lock file")
    return found


def render(profile: str = "base") -> str:
    """Return the transformed lock content (uv export, local versions stripped)."""
    if profile not in PROFILES:
        raise SystemExit(f"FAIL: unknown profile {profile!r}; expected one of {sorted(PROFILES)}")
    extra_flags, _ = PROFILES[profile]
    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / "export.txt"
        completed = subprocess.run(
            [_uv(), *EXPORT_ARGS, *extra_flags, "--output-file", str(target)],
            cwd=REPO_ROOT, capture_output=True, text=True, timeout=900,
        )
        if completed.returncode != 0:
            raise SystemExit(f"FAIL: uv export failed:\n{completed.stdout}{completed.stderr}")
        raw = target.read_text(encoding="utf-8")

    lines: list[str] = []
    for line in raw.splitlines():
        match = _LOCAL_VERSION.match(line)
        if match:
            line = (
                f"{match.group('name')}=={match.group('version')}{match.group('rest')}"
            )
        lines.append(line)
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="regenerate the hash-locked requirements files")
    parser.add_argument("--profile", choices=sorted(PROFILES), default="base",
                        help="which dependency surface to render (default: base)")
    parser.add_argument("--check", action="store_true", help="verify instead of writing")
    parser.add_argument("--output", default=None,
                        help="override the output path (default: the profile's committed file)")
    args = parser.parse_args(argv)

    rendered = render(args.profile)
    target = Path(args.output) if args.output else REPO_ROOT / PROFILES[args.profile][1]
    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current == rendered or _semantic_pins(current) == _semantic_pins(rendered):
            print(f"LOCK: {target.name} up to date")
            return 0
        print(f"FAIL: {target.name} is stale; run export_lock.py --profile {args.profile}", file=sys.stderr)
        return 1

    target.write_text(rendered, encoding="utf-8")
    pins = len([line for line in rendered.splitlines() if "==" in line or line.startswith((" ", "\\"))])
    print(f"LOCK: wrote {target} ({len(rendered.splitlines())} lines, {pins} pin segments)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
